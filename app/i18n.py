def language_names():
    return [name for _code, name in LANGUAGES]


def current_code():
    """The interface language, if it is one the app is finished in.

    A language chosen in an earlier release stays in the settings file
    after it stops being offered, and honouring it would leave exactly the
    window this change exists to remove: translated headings over English
    paragraphs, on a machine whose owner has no way to switch back because
    the picker is gone.
    """
    stored = str(config.CONFIG.get("app_language", "en") or "en")
    offered = {code for code, _name in LANGUAGES}
    return stored if stored in offered else "en"


def current_name():
    code = current_code()
    for candidate, name in LANGUAGES:
        if candidate == code:
            return name
    return "English"


def set_language_by_name(display_name):
    for code, name in LANGUAGES:
        if name == display_name:
            config.CONFIG.set("app_language", code)
            return code
    return current_code()


def t(text):
    """Translate an interface string, or return it unchanged.

    Missing entries fall through to English on purpose: a half-translated
    window is readable, a window full of blanks is not.
    """
    table = STRINGS.get(current_code())
    if not table:
        return text
    return table.get(text, text)
